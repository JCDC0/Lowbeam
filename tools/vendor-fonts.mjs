/**
 * Copies the game's extra fonts from node_modules into assets/fonts/ and writes assets/fonts/fonts.css,
 * the same way three.js is vendored: the page loads nothing from the network. Run after
 * `npm install` when a font package changes: `node tools/vendor-fonts.mjs`.
 *
 * - DSEG7 Classic and DSEG14 Classic (keshikan, OFL): seven and fourteen segment digits for the
 *   digital speedometers.
 * - Share Tech Mono (OFL): monospace readouts.
 * - Dela Gothic One (OFL): heavy display face for police and race banners, with Japanese.
 * - M PLUS 1p (OFL): Japanese text on signs and in the UI, regular and bold.
 * - Orbitron (OFL): a wide geometric face for the title and menu headings, bold and black.
 * - Teko (OFL): a condensed sport face for big race and pursuit numbers, latin only.
 *
 * The CJK fonts come split into about 120 pieces per weight with a unicode-range each, so the browser
 * only downloads the pieces whose characters a page actually uses.
 */

import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const nm = path.join(root, 'node_modules');
const out = path.join(root, 'assets', 'fonts');
const files = path.join(out, 'files');
fs.mkdirSync(files, { recursive: true });

let css = '/* Generated by tools/vendor-fonts.mjs. Licenses: assets/fonts/LICENSES.md. */\n';

/** @param {string} family @param {string} file @param {number} weight */
function dseg(family, dir, file, weight) {
  fs.copyFileSync(path.join(nm, 'dseg', 'fonts', dir, file), path.join(files, file));
  css += `@font-face {\n  font-family: '${family}';\n  font-style: normal;\n  font-display: block;\n  font-weight: ${weight};\n  src: url(./files/${file}) format('woff2');\n}\n`;
}
dseg('DSEG7 Classic', 'DSEG7-Classic', 'DSEG7Classic-Regular.woff2', 400);
dseg('DSEG7 Classic', 'DSEG7-Classic', 'DSEG7Classic-Bold.woff2', 700);
dseg('DSEG14 Classic', 'DSEG14-Classic', 'DSEG14Classic-Regular.woff2', 400);
dseg('DSEG14 Classic', 'DSEG14-Classic', 'DSEG14Classic-Bold.woff2', 700);

/**
 * One Fontsource stylesheet: its rules go into fonts.css with the woff2 sources only, and the files
 * they name are copied.
 * @param {string} pkg @param {string} sheet
 */
function fontsource(pkg, sheet) {
  const dir = path.join(nm, '@fontsource', pkg);
  const text = fs.readFileSync(path.join(dir, sheet), 'utf8');
  const rules = text.replace(/src: url\(\.\/files\/([^)]+\.woff2)\) format\('woff2'\), url\([^)]+\) format\('woff'\);/g, (_, f) => {
    fs.copyFileSync(path.join(dir, 'files', f), path.join(files, f));
    return `src: url(./files/${f}) format('woff2');`;
  });
  css += rules.replace(/font-display: swap;/g, 'font-display: block;') + '\n';
}
fontsource('share-tech-mono', '400.css');
fontsource('dela-gothic-one', '400.css');
fontsource('m-plus-1p', '400.css');
fontsource('m-plus-1p', '700.css');
fontsource('orbitron', '700.css');
fontsource('orbitron', '900.css');
fontsource('teko', 'latin-500.css');
fontsource('teko', 'latin-700.css');
fs.copyFileSync(path.join(nm, '@fontsource', 'orbitron', 'LICENSE'), path.join(out, 'Orbitron-OFL.txt'));
fs.copyFileSync(path.join(nm, '@fontsource', 'teko', 'LICENSE'), path.join(out, 'Teko-OFL.txt'));

fs.writeFileSync(path.join(out, 'fonts.css'), css);
fs.copyFileSync(path.join(nm, 'dseg', 'DSEG-LICENSE.txt'), path.join(out, 'DSEG-LICENSE.txt'));
const n = fs.readdirSync(files).length;
const bytes = fs.readdirSync(files).reduce((a, f) => a + fs.statSync(path.join(files, f)).size, 0);
console.log(`${n} font files, ${(bytes / 1e6).toFixed(1)} MB, fonts.css ${(css.length / 1e3).toFixed(0)} kB`);
